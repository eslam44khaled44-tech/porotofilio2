const $ = (selector, parent = document) =>
  parent.querySelector(selector);

const $$ = (selector, parent = document) =>
  [...parent.querySelectorAll(selector)];


/* ==========================================
   3. LANGUAGE SWITCHER
========================================== */

let currentLanguage = localStorage.getItem("portfolioLanguage") || "en";

function updateLanguage(language) {
  if (!translations[language]) {
    language = "en";
  }

  currentLanguage = language;

  const html = document.documentElement;
  const body = document.body;

  // Update document language and direction
  html.lang = language;
  html.dir = language === "ar" ? "rtl" : "ltr";

  // Add a class for optional language-specific styling
  body.classList.toggle("arabic-mode", language === "ar");

  // Update every element containing a translation key
  $$("[data-i18n]").forEach((element) => {
    const key = element.dataset.i18n;
    const translatedText = translations[language][key];

    if (translatedText !== undefined) {
      element.textContent = translatedText;
    }
  });

  // Update the language button
  const languageButton = $("#language-toggle");

  if (languageButton) {
    languageButton.textContent = translations[language].language;
    languageButton.setAttribute(
      "aria-label",
      language === "en"
        ? "Switch language to Arabic"
        : "تغيير اللغة إلى الإنجليزية"
    );
  }

  // Remember the selected language
  try {
    localStorage.setItem("portfolioLanguage", language);
  } catch (error) {
    console.warn("Language preference could not be saved.");
  }

  // Update browser tab title
  document.title =
    language === "ar"
      ? "سوسن محمد | مطورة واجهات أمامية"
      : "Sawsan Mohamed | Front-End Developer";

  // Notify the rest of the page
  document.dispatchEvent(
    new CustomEvent("portfolio:languagechange", {
      detail: { language }
    })
  );
}


function initializeLanguageSwitcher() {
  const languageButton = $("#language-toggle");

  if (!languageButton) {
    console.warn(
      'Language button not found. Add id="language-toggle" to your HTML button.'
    );

    return;
  }

  languageButton.addEventListener("click", () => {
    const nextLanguage =
      currentLanguage === "en" ? "ar" : "en";

    updateLanguage(nextLanguage);
  });

  updateLanguage(currentLanguage);
}


/* ==========================================
   4. MOBILE NAVIGATION
========================================== */

function initializeMobileMenu() {
  const menuButton = $("#menu-toggle");
  const navigation = $("#nav-links");

  if (!menuButton || !navigation) {
    console.warn(
      "Mobile navigation elements are missing. Check your HTML IDs."
    );

    return;
  }

  function setMenuState(isOpen) {
    navigation.classList.toggle("active", isOpen);
    menuButton.classList.toggle("active", isOpen);

    menuButton.setAttribute("aria-expanded", String(isOpen));

    navigation.setAttribute("aria-hidden", String(!isOpen));

    // Prevent keyboard focus on hidden navigation links
    if (window.matchMedia("(max-width: 760px)").matches) {
      navigation.inert = !isOpen;
    } else {
      navigation.inert = false;
    }
  }

  menuButton.setAttribute("aria-expanded", "false");
  navigation.setAttribute("aria-hidden", "false");

  setMenuState(false);

  menuButton.addEventListener("click", () => {
    const isOpen = !navigation.classList.contains("active");

    setMenuState(isOpen);
  });

  // Close menu after clicking a navigation link
  $$("#nav-links a").forEach((link) => {
    link.addEventListener("click", () => {
      setMenuState(false);
    });
  });

  // Close menu when clicking outside it
  document.addEventListener("click", (event) => {
    const clickedInsideNavigation =
      navigation.contains(event.target);

    const clickedMenuButton =
      menuButton.contains(event.target);

    if (!clickedInsideNavigation && !clickedMenuButton) {
      setMenuState(false);
    }
  });

  // Close menu with Escape
  document.addEventListener("keydown", (event) => {
    if (event.key === "Escape") {
      setMenuState(false);
      menuButton.focus();
    }
  });

  // Restore normal navigation when switching to desktop
  window.addEventListener("resize", () => {
    if (window.matchMedia("(min-width: 761px)").matches) {
      setMenuState(false);
      navigation.inert = false;
      navigation.setAttribute("aria-hidden", "false");
    }
  });
}


/* ==========================================
   5. BACKGROUND STARS & BUBBLES
========================================== */

function createBackgroundEffects() {
  let background = $(".stars-background");

  // Create background container if it doesn't exist
  if (!background) {
    background = document.createElement("div");
    background.className = "stars-background";

    background.setAttribute("aria-hidden", "true");

    document.body.prepend(background);
  }

  // Avoid generating particles more than once
  if (background.dataset.initialized === "true") {
    return;
  }

  background.dataset.initialized = "true";

  const reducedMotion = window.matchMedia(
    "(prefers-reduced-motion: reduce)"
  ).matches;

  const smallScreen = window.matchMedia(
    "(max-width: 600px)"
  ).matches;

  const starCount = smallScreen ? 22 : 45;
  const bubbleCount = smallScreen ? 5 : 10;

  const fragment = document.createDocumentFragment();

  // Create tiny glowing stars
  for (let i = 0; i < starCount; i++) {
    const star = document.createElement("span");

    star.className = "star-particle";

    star.style.left = `${Math.random() * 100}%`;
    star.style.top = `${Math.random() * 100}%`;

    star.style.animationDelay =
      `${Math.random() * 5}s`;

    star.style.animationDuration =
      `${3 + Math.random() * 5}s`;

    const size = 1 + Math.random() * 2;

    star.style.width = `${size}px`;
    star.style.height = `${size}px`;

    fragment.appendChild(star);
  }

  // Create subtle floating bubbles
  for (let i = 0; i < bubbleCount; i++) {
    const bubble = document.createElement("span");

    bubble.className = "bubble-particle";

    bubble.style.left = `${Math.random() * 100}%`;
    bubble.style.top = `${Math.random() * 100}%`;

    const size = 8 + Math.random() * 22;

    bubble.style.setProperty(
      "--bubble-size",
      `${size}px`
    );

    bubble.style.setProperty(
      "--bubble-duration",
      `${8 + Math.random() * 12}s`
    );

    bubble.style.animationDelay =
      `${Math.random() * 8}s`;

    fragment.appendChild(bubble);
  }

  background.appendChild(fragment);

  // Respect the visitor's motion preferences
  if (reducedMotion) {
    background.querySelectorAll("*").forEach((particle) => {
      particle.style.animation = "none";
    });
  }
}


/* ==========================================
   6. SCROLL REVEAL ANIMATIONS
========================================== */

function initializeScrollReveal() {
  const revealElements = $$(".reveal");

  const reducedMotion = window.matchMedia(
    "(prefers-reduced-motion: reduce)"
  ).matches;

  if (reducedMotion || !("IntersectionObserver" in window)) {
    revealElements.forEach((element) => {
      element.classList.add("visible");
    });

    return;
  }

  const observer = new IntersectionObserver(
    (entries, observerInstance) => {
      entries.forEach((entry) => {
        if (entry.isIntersecting) {
          entry.target.classList.add("visible");

          observerInstance.unobserve(entry.target);
        }
      });
    },
    {
      threshold: 0.12,
      rootMargin: "0px 0px -35px 0px"
    }
  );

  revealElements.forEach((element) => {
    observer.observe(element);
  });
}


/* ==========================================
   7. PROFILE IMAGE FALLBACK
========================================== */

function initializeProfileImage() {
  const image = $("#profile-image");
  const fallback = $("#profile-fallback");

  if (!image || !fallback) {
    return;
  }

  function showFallback() {
    image.hidden = true;
    fallback.hidden = false;
  }

  function showImage() {
    image.hidden = false;
    fallback.hidden = true;
  }

  image.addEventListener("error", showFallback);
  image.addEventListener("load", showImage);

  // Handle an image that failed before JavaScript ran
  if (image.complete) {
    if (image.naturalWidth === 0) {
      showFallback();
    } else {
      showImage();
    }
  }
}


/* ==========================================
   8. ACTIVE NAVIGATION LINK
========================================== */

function initializeActiveNavigation() {
  const sections = $$("main section[id]");
  const navigationLinks = $$("#nav-links a[href^='#']");

  if (!sections.length || !navigationLinks.length) {
    return;
  }

  if (!("IntersectionObserver" in window)) {
    return;
  }

  const sectionObserver = new IntersectionObserver(
    (entries) => {
      entries.forEach((entry) => {
        if (!entry.isIntersecting) {
          return;
        }

        const activeId = entry.target.id;

        navigationLinks.forEach((link) => {
          const isActive =
            link.getAttribute("href") === `#${activeId}`;

          if (isActive) {
            link.setAttribute("aria-current", "location");
          } else {
            link.removeAttribute("aria-current");
          }
        });
      });
    },
    {
      rootMargin: "-30% 0px -55% 0px",
      threshold: 0
    }
  );

  sections.forEach((section) => {
    sectionObserver.observe(section);
  });
}


